package com.yesman.akytheralabs;

import com.yesman.akythera.core.blueprint.EntityPatchBlueprint;
import com.yesman.akythera.core.blueprint.script.DataDrivenAnimatorScript;
import com.yesman.akythera.core.blueprint.script.ScriptVariables;
import com.yesman.akythera.core.registry.AkytheraRegistries;
import com.yesman.akythera.core.util.helper.ParseUtils;
import com.yesman.akytheralabs.dataholder.DTOProvider;
import com.yesman.akytheralabs.dataholder.DataHolder;
import com.yesman.akytheralabs.dataholder.ProjectObjectRegistry;
import com.yesman.akytheralabs.dataholder.entitypatch.EntityPatchBlueprintHolder;
import com.yesman.akytheralabs.dataholder.entitypatch.component.ComponentSourceProvider;
import com.yesman.akytheralabs.dataholder.entitypatch.component.EntityPatchComponentHolders;
import freemarker.template.Template;
import freemarker.template.TemplateException;
import net.minecraft.core.Registry;
import net.minecraft.resources.ResourceKey;
import org.jspecify.annotations.NullMarked;

import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

@NullMarked
public final class FreemarkerExporter {
    private FreemarkerExporter() {}

    /// Sub-directory (and sub-package) the generated [net.minecraft.data.DataProvider] classes land in.
    private static final String PROVIDERS_DIR = "providers";
    /// Sub-directory (and sub-package) the generated `*AnimatorScript` classes land in.
    private static final String SCRIPTS_DIR = "scripts\\animator";
    /// Sub-directory (and sub-package) the generated `*EntityPatchScript` classes land in.
    private static final String PATCHES_DIR = "scripts\\entitypatches";

    /// The owner handle [com.yesman.akytheralabs.ScriptNodeSourceCompiler] lowers a graph `self` to,
    /// per script kind: an animator script's field is `animator`, an entity-patch script's is `owner`.
    private static final String ANIMATOR_SELF = "this.animator";
    private static final String ENTITY_PATCH_SELF = "this.owner";

    /// Per-registry code-generation descriptor: which template to render, the variable name the template
    /// iterates over (`<#list ${collectionVar} as ...>`), and the suffix appended to the project's
    /// PascalCase name to form the generated class (and thus the output file name).
    private record SourceTemplate(String templateFile, String collectionVar, String classSuffix) {}

    /// One entry per registry type the exporter can generate. Add a row here (plus its `.ftl`) to make a
    /// new registry type exportable.
    private static final Map<ResourceKey<? extends Registry<?>>, SourceTemplate> FTL_FILES = Map.of(
        AkytheraRegistries.DataPack.ANIM_SEQUENCE_KEY,
        new SourceTemplate("animation_sequence_template.ftl", "sequences", "AnimationSequences"),

        AkytheraRegistries.DataPack.BLEND_SPACE_2D_KEY,
        new SourceTemplate("blend_space_2d_template.ftl", "blend_spaces", "BlendSpace2Ds"),

        AkytheraRegistries.DataPack.ANIM_MONTAGE_KEY,
        new SourceTemplate("animation_montage_template.ftl", "montages", "AnimationMontages")
    );

    /// Export the project as [net.minecraft.data.DataProvider] source. JSON objects are generated by each
    /// mod platform's datagen task once the generated providers are compiled into the target mod.
    ///
    /// Applies globally to every registry type registered in [#FTL_FILES]:
    /// - `sourceCodeRoot` — directory the generated `.java` files are written into.
    /// - `packageName` — fills the `${package}` token in every template.
    public static void exportProject(AkytheraProject project, Path sourceCodeRoot, String packageName) {
        String modid = project.getProjectName();
        String typeName = ParseUtils.camelToSpacedPascal(modid);

        Path providersRoot = sourceCodeRoot.resolve(PROVIDERS_DIR);
        String providersPackage = subPackage(packageName, PROVIDERS_DIR);
        boolean providersDirReady = false;

        for (Map.Entry<ResourceKey<? extends Registry<?>>, SourceTemplate> e : FTL_FILES.entrySet()) {
            SourceTemplate descriptor = e.getValue();
            List<Map<String, Object>> entries = collectEntries(project, e.getKey());

            // Skip registries the project never populated — no entries means no provider class.
            if (entries.isEmpty()) {
                continue;
            }

            // Create the providers directory lazily, only once a registry actually has output.
            if (!providersDirReady) {
                try {
                    Files.createDirectories(providersRoot);
                } catch (IOException ex) {
                    AkytheraLabs.LOGGER.error("Failed to create export directory {}", providersRoot, ex);
                    return;
                }
                providersDirReady = true;
            }

            String className = typeName + descriptor.classSuffix();

            Map<String, Object> model = new HashMap<>();
            model.put("package", providersPackage);
            model.put("modid", modid);
            model.put("className", className);
            model.put(descriptor.collectionVar(), entries);

            Path outputFile = providersRoot.resolve(className + ".java");

            try {
                Template template = SourceTemplateEngine.getTemplate(descriptor.templateFile());

                try (Writer writer = Files.newBufferedWriter(outputFile, StandardCharsets.UTF_8)) {
                    template.process(model, writer);
                }

                AkytheraLabs.LOGGER.info("Exported {} -> {}", e.getKey().identifier(), outputFile);
            } catch (IOException | TemplateException ex) {
                AkytheraLabs.LOGGER.error("Failed to export {} from template {}", e.getKey().identifier(), descriptor.templateFile(), ex);
            }
        }

        exportAnimatorScripts(project, sourceCodeRoot, packageName);
        exportEntityPatchScripts(project, sourceCodeRoot, packageName);
    }

    /// Unlike the [#FTL_FILES] registries (one provider class per registry), each animator-script
    /// entry becomes its own `<PascalCaseEntryName>AnimatorScript.java` — a handwritten-style
    /// [com.yesman.akythera.core.blueprint.script.AnimatorScript] implementation. The entry's flat
    /// graphs are first lowered to the runtime blueprint (the holder's `makeObject`, the same
    /// compile the datapack export uses), then [ScriptNodeSourceCompiler] renders each of the three
    /// flows into the method bodies of `animator_script_template.ftl`. A per-entry failure is
    /// logged and skipped so one broken graph can't abort the export.
    private static void exportAnimatorScripts(AkytheraProject project, Path sourceCodeRoot, String packageName) {
        ProjectObjectRegistry<DataDrivenAnimatorScript.AnimatorScriptBlueprint, DataHolder<DataDrivenAnimatorScript.AnimatorScriptBlueprint>> registry =
            project.getModifiableRegistry(AkytheraRegistries.DataPack.ANIMATOR_SCRIPT_KEY);

        // No registry, or no scripts authored — emit nothing (and don't create the scripts dir).
        if (registry == null || registry.dataHolderEntrySet().isEmpty()) {
            return;
        }

        Path scriptsRoot = sourceCodeRoot.resolve(SCRIPTS_DIR);
        try {
            Files.createDirectories(scriptsRoot);
        } catch (IOException e) {
            AkytheraLabs.LOGGER.error("Failed to create export directory {}", scriptsRoot, e);
            return;
        }

        String scriptsPackage = subPackage(packageName, SCRIPTS_DIR);

        for (var entry : registry.dataHolderEntrySet()) {
            String idPath = entry.getKey().identifier().getPath();
            String className = ParseUtils.pascalCase(idPath) + "AnimatorScript";
            Path outputFile = scriptsRoot.resolve(className + ".java");

            try {
                DataDrivenAnimatorScript.AnimatorScriptBlueprint blueprint = entry.getValue().makeObject();

                List<String> memberVariables = blueprint.variables().stream()
                    .map(ScriptVariables.VariableInfo::name)
                    .toList();

                // Context parameter names must match the engine's locals (see DataDrivenAnimatorScript):
                // they become the generated methods' parameter names, so every ContextVariableAccessNode
                // resolves to a real Java identifier.
                Map<String, Object> model = new HashMap<>();
                model.put("package", scriptsPackage);
                model.put("modid", project.getProjectName());
                model.put("className", className);
                model.put("fields", animatorFields(blueprint.variables()));
                model.put("constructBody", ScriptNodeSourceCompiler.compileFlow(
                    blueprint.construct(), memberVariables, List.of("animLayerMap", "poseCaches", "animator"), ANIMATOR_SELF));
                model.put("updateBody", ScriptNodeSourceCompiler.compileFlow(
                    blueprint.update(), memberVariables, List.of("frameTime", "partialTick"), ANIMATOR_SELF));
                model.put("poseBody", ScriptNodeSourceCompiler.compileReturningFlow(
                    blueprint.poseGetter(), memberVariables, List.of("layers"), ANIMATOR_SELF, "Pose.EMPTY_POSE"));

                Template template = SourceTemplateEngine.getTemplate("animator_script_template.ftl");

                try (Writer writer = Files.newBufferedWriter(outputFile, StandardCharsets.UTF_8)) {
                    template.process(model, writer);
                }

                AkytheraLabs.LOGGER.info("Exported {} -> {}", entry.getKey().identifier(), outputFile);
            } catch (Exception ex) {
                AkytheraLabs.LOGGER.error("Failed to export animator script {} as source", entry.getKey().identifier(), ex);
            }
        }
    }

    /// The entity-patch analogue of [#exportAnimatorScripts]: each entity-patch entry becomes its own
    /// `<PascalCaseEntryName>EntityPatchScript.java`, a handwritten-style
    /// [com.yesman.akythera.core.blueprint.script.EntityPatchScript]. The entry's flat Event Graph is
    /// lowered to the runtime [EntityPatchBlueprint] (the holder's `makeObject`, the same compile the
    /// datapack export uses); [ScriptNodeSourceCompiler] renders its three flows — `onConstruct`,
    /// `onJoinWorld` (context param `level`, matching [com.yesman.akythera.core.blueprint.script.DataDrivenEntityPatchScript]),
    /// `update` — with `self` bound to the generated class's `owner` field.
    ///
    /// The one shape unlike the animator: components aren't graph-generated but a plain list, so each
    /// attached component holder renders its own constructor expression ([#componentSources]) that the
    /// template collects into `componentsToAttach()`. A per-entry failure is logged and skipped.
    private static void exportEntityPatchScripts(AkytheraProject project, Path sourceCodeRoot, String packageName) {
        ProjectObjectRegistry<EntityPatchBlueprint, DataHolder<EntityPatchBlueprint>> registry =
            project.getModifiableRegistry(AkytheraRegistries.DataPack.ENTITY_PATCH_KEY);

        // No registry, or no patches authored — emit nothing (and don't create the patches dir).
        if (registry == null || registry.dataHolderEntrySet().isEmpty()) {
            return;
        }

        Path patchesRoot = sourceCodeRoot.resolve(PATCHES_DIR);
        try {
            Files.createDirectories(patchesRoot);
        } catch (IOException e) {
            AkytheraLabs.LOGGER.error("Failed to create export directory {}", patchesRoot, e);
            return;
        }

        String patchesPackage = subPackage(packageName, PATCHES_DIR);

        for (var entry : registry.dataHolderEntrySet()) {
            // Name from the entry's leaf only, not its directory: `minecraft/player` -> `PlayerPatchScript`
            // (the folder is organisational, not part of the type's identity).
            String idPath = entry.getKey().identifier().getPath();
            String entryName = idPath.substring(idPath.lastIndexOf('/') + 1);
            String className = ParseUtils.pascalCase(entryName) + "PatchScript";
            Path outputFile = patchesRoot.resolve(className + ".java");

            try {
                DataHolder<EntityPatchBlueprint> holder = entry.getValue();
                EntityPatchBlueprint blueprint = holder.makeObject();

                List<String> memberVariables = blueprint.variables().stream()
                    .map(ScriptVariables.VariableInfo::name)
                    .toList();

                // Context parameter names match the engine's DataDrivenEntityPatchScript locals: the
                // param-less onConstruct/update seed nothing, onJoinWorld seeds `level` (setValue).
                Map<String, Object> model = new HashMap<>();
                model.put("package", patchesPackage);
                model.put("modid", project.getProjectName());
                model.put("className", className);
                model.put("fields", animatorFields(blueprint.variables()));
                model.put("constructBody", ScriptNodeSourceCompiler.compileFlow(
                    blueprint.onConstruct(), memberVariables, List.of(), ENTITY_PATCH_SELF));
                model.put("joinWorldBody", ScriptNodeSourceCompiler.compileFlow(
                    blueprint.onJoinWorld(), memberVariables, List.of("level"), ENTITY_PATCH_SELF));
                model.put("updateBody", ScriptNodeSourceCompiler.compileFlow(
                    blueprint.update(), memberVariables, List.of(), ENTITY_PATCH_SELF));
                model.put("components", componentSources(holder));

                Template template = SourceTemplateEngine.getTemplate("entity_patch_script_template.ftl");

                try (Writer writer = Files.newBufferedWriter(outputFile, StandardCharsets.UTF_8)) {
                    template.process(model, writer);
                }

                AkytheraLabs.LOGGER.info("Exported {} -> {}", entry.getKey().identifier(), outputFile);
            } catch (Exception ex) {
                AkytheraLabs.LOGGER.error("Failed to export entity patch script {} as source", entry.getKey().identifier(), ex);
            }
        }
    }

    /// The attached components' constructor expressions, in the holder's stored order — each rendered
    /// from its own `components/<type>.ftl` fragment ([ComponentSourceProvider#toSourceCode]). A
    /// component type without source support (or an unexpected non-holder) emits a `/* TODO */` marker
    /// rather than aborting the whole patch's export.
    private static List<String> componentSources(DataHolder<EntityPatchBlueprint> holder) {
        if (!(holder instanceof EntityPatchBlueprintHolder patchHolder)) {
            return List.of();
        }

        return patchHolder.getComponents().values().stream()
            .map(component -> component instanceof ComponentSourceProvider provider
                ? provider.toSourceCode()
                : "null /* TODO: component " + EntityPatchComponentHolders.typeIdOf(component)
                    + " has no components/*.ftl source template */")
            .toList();
    }

    /// Template rows for the generated `@ScriptField` members: Java type simple name, field name,
    /// and (when the variable carries one) its default value as a Java literal.
    private static List<Map<String, Object>> animatorFields(List<ScriptVariables.VariableInfo> variables) {
        return variables.stream()
            .<Map<String, Object>>map(variable -> {
                Map<String, Object> row = new LinkedHashMap<>();
                row.put("type", ParseUtils.unwrapPrimitive(variable.type().type()).getSimpleName());
                row.put("name", variable.name());

                String defaultLiteral = ScriptNodeSourceCompiler.defaultValueLiteral(variable);
                if (defaultLiteral != null) row.put("defaultValue", defaultLiteral);

                return row;
            })
            .toList();
    }

    /// Build the template model rows for one registry: every entry the project created for that registry,
    /// id-path sorted for stable output. Each row exposes `asId` (the createId argument), `asVariableName`
    /// (the `public static final ResourceKey` field name), and `dto` — the entry holder's own
    /// [DTOProvider#getDTO], the custom token map the template splices into the generated source.
    private static List<Map<String, Object>> collectEntries(
        AkytheraProject project, ResourceKey<? extends Registry<?>> registryKey
    ) {
        @SuppressWarnings("unchecked")
        ResourceKey<? extends Registry<Object>> typed = (ResourceKey<? extends Registry<Object>>) registryKey;
        ProjectObjectRegistry<Object, ?> registry = project.getModifiableRegistry(typed);

        if (registry == null) {
            return List.of();
        }

        return registry.dataHolderEntrySet().stream()
            .sorted(Comparator.comparing(entry -> entry.getKey().identifier().getPath()))
            .map(entry -> {
                String path = entry.getKey().identifier().getPath();
                DataHolder<?> holder = entry.getValue();

                if (!(holder instanceof DTOProvider provider)) {
                    throw new IllegalStateException(
                        holder.getClass().getName() + " must implement DTOProvider to be exportable"
                    );
                }

                Map<String, Object> row = new LinkedHashMap<>();
                row.put("asId", path);
                row.put("asVariableName", toVariableName(path));
                row.put("dto", provider.getDTO());

                return row;
            })
            .toList();
    }

    /// Append a sub-package segment to the chosen base package, tolerating a blank base (the modal
    /// leaves the package field empty when the export dir isn't under `src/main/java`).
    private static String subPackage(String base, String segment) {
        return base.isBlank() ? segment : base + "." + segment.replaceAll("\\\\", ".");
    }

    /// `"humanoid/walk_forward"` -> `"HUMANOID_WALK_FORWARD"`: every non-alphanumeric run becomes a single
    /// underscore, then upper-cased — the SCREAMING_SNAKE_CASE convention used for the generated key fields.
    private static String toVariableName(String idPath) {
        return idPath.replaceAll("[^A-Za-z0-9]+", "_").toUpperCase(Locale.ROOT);
    }
}
